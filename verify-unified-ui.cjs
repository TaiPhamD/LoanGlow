const { chromium, expect } = require('@playwright/test');
(async () => {
 const browser = await chromium.launch();
 try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 1400 } });
  await page.goto(process.env.TEST_URL || 'http://localhost:8081', { waitUntil: 'networkidle' });
  await page.evaluate(() => localStorage.clear());
  await page.reload({ waitUntil: 'networkidle' });
  const rate = page.getByRole('textbox', { name: 'Interest rate', exact: true });
  await expect(rate).toHaveCount(1);
  const advanced = page.getByTestId('loan-mode-switch');
  await advanced.click();
  await expect(page.getByTestId('basic-inputs').getByRole('textbox', { name: 'Interest rate', exact: true })).toHaveCount(0);
  await expect(page.getByTestId('advanced-inputs').getByRole('textbox', { name: 'Interest rate', exact: true })).toHaveValue('6.5');
  await rate.fill('6.25');
  await page.getByRole('button', { name: 'Adjustable rate', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Initial interest rate', exact: true })).toHaveCount(0);
  await advanced.click();
  await expect(rate).toHaveCount(1);
  await advanced.click();
  await expect(rate).toHaveValue('6.25');
  await page.getByRole('button', { name: 'After-adjustment scenario', exact: true }).click();
  await page.getByRole('textbox', { name: 'Hypothetical adjusted rate', exact: true }).fill('8.5');
  const summary = page.getByTestId('payment-summary');
  await expect(summary.getByText('Estimated monthly payment', { exact: true })).toHaveCount(1);
  await expect(summary.getByText('First 7 years', { exact: true })).toBeVisible();
  await expect(summary.getByText('Scenario · month 85', { exact: true })).toBeVisible();
  await expect(page.getByTestId('advanced-inputs').getByText(/Hypothetical P&I/)).toHaveCount(0);
  const amount = async id => Number((await page.getByTestId(id).innerText()).replace(/[^\d.-]/g, ''));
  const initial = await amount('initial-total');
  const future = await amount('scenario-total');
  await page.getByRole('textbox', { name: 'HOA', exact: true }).fill('100');
  expect(await amount('initial-total')).toBe(initial + 100);
  expect(await amount('scenario-total')).toBe(future + 100);
  await advanced.click();
  await expect(page.getByTestId('scenario-total')).toHaveCount(0);
  await page.waitForTimeout(500);
  await page.reload({ waitUntil: 'networkidle' });
  await expect(rate).toHaveCount(1);
  await expect(page.getByTestId('scenario-total')).toHaveCount(0);
  await advanced.click();
  await page.getByRole('textbox', { name: 'Hypothetical adjusted rate', exact: true }).fill('bad');
  await expect(page.getByTestId('scenario-total')).toHaveCount(0);
  await expect(summary.getByText(/Enter a valid hypothetical rate/)).toBeVisible();
  await page.getByRole('textbox', { name: 'Hypothetical adjusted rate', exact: true }).fill('8.5');
  await expect(page.getByTestId('advanced-inputs')).toHaveCSS('opacity', '1');
  await page.getByRole('textbox', { name: 'Hypothetical adjusted rate', exact: true }).blur();
  await page.screenshot({ path: 'verification-unified-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 2000 });
  await page.screenshot({ path: 'verification-unified-phone.png', fullPage: true });
  await page.getByRole('button', { name: 'Fixed rate', exact: true }).click();
  await advanced.click();
  await expect(rate).toHaveCount(1);
  await expect(rate).toHaveValue('6.25');
  await expect(page.getByTestId('scenario-total')).toHaveCount(0);
  console.log('PASS: single relocated Interest rate, unified comparable totals, invalid scenario, collapse and persistence');
 } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
